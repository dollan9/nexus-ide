/**
 * chunker.ts — code-aware chunking för RAG-kodbasminnet (FAS 3.5, P0:
 * "Code-aware chunking med bevarade radnummer och symbolnamn").
 *
 * Varför handskriven linjeskann i stället för en AST-parser:
 *   Core-paketet får inte lägga till ett parse-beroende (träd, tree-sitter, swc) för
 *   den här features skull — RAM-beläggningen är hård (5 GB ledig) och bygget måste
 *   förbli dependency-fritt. Vi behöver BARA regiongränser (start/end + symbolnamn),
 *   inte ett fullständigt AST. Därför sparas radnumren exakt: varje region binds mot
 *   de faktiska raderna i filen och testet (rag-chunker.test.ts) öppnar filen och
 *   jämför — gissade radnummer är ett godkänt testfel, inte en acceptabel impl.
 *
 * Garantier:
 *   - Ingen chunk överskrider den angivna token-budgeten (rad-fönster med overlap,
 *     och en enskild för lång rad skärs i teckenbitar som behåller sitt radnummer).
 *   - Binära, genererade och låsta filer skutas (skipReason()).
 *   - Ignore-reglerna äger WorkspaceService — indexern hämtar filerna via den, den
 *     här modulen tar bara emot (path, language, content) och hoppar aldrig över
 *     kataloger själv.
 */

/** Chunkens ursprung — används för diagnos och för att välja truncering i context.ts. */
export type ChunkKind = "symbol" | "section" | "document" | "body" | "window";

export type ChunkFamily = "code-ts" | "code-py" | "markdown" | "data" | "generic";

/** En chunk före embedding. `id` är deterministisk: samma fil + rader ger samma id. */
export interface ChunkDraft {
  readonly id: string;
  readonly path: string;
  readonly startLine: number;
  readonly endLine: number;
  readonly text: string;
  readonly symbol?: string;
  readonly kind: ChunkKind;
}

export interface ChunkerOptions {
  /** Hårddag runt ~250 tokens per chunk; coding-agentens kontextblock håller sig små. */
  readonly maxChunkTokens?: number;
  /** Rader som upprepas mellan fönster när en region måste delas. */
  readonly overlapLines?: number;
  /** Tak per fil — skyddar mot pathological huge files under pågående indexering. */
  readonly maxChunksPerFile?: number;
}

export const DEFAULT_MAX_CHUNK_TOKENS = 250;
export const DEFAULT_OVERLAP_LINES = 3;
export const DEFAULT_MAX_CHUNKS_PER_FILE = 400;

/** Rådata som skutas: binärt, lås/lock-filer, genererad kod och kända bundle-namn. */
const SKIP_BASENAME_RE = /^(package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|Gemfile\.lock|poetry\.lock|Pipfile\.lock|composer\.lock|Cargo\.lock|uv\.lock)$/i;
const SKIP_BASENAME_RE2 = /(\.min\.(js|css|mjs)$)|(\.d\.ts\.map$)|(\.map$)|(\.pack$)|(\.bundle\.js$)/i;
const GENERATED_HINTS = [
  "@generated",
  "code generated by",
  "generated by",
  "do not edit",
  "autogenerated",
  "auto-generated",
  "this file was generated",
];

/**ungefär 4 tecken per token; kod har mer punkutation än prose → 3.6 ger en konservativ överskattning. */
const CHARS_PER_TOKEN = 3.6;

export function estimateTokens(text: string): number {
  if (text.length === 0) return 0;
  return Math.ceil(text.length / CHARS_PER_TOKEN);
}

/** Bestäm Which family is used */
export function chunkFamilyOf(language: string): ChunkFamily {
  const lang = language.toLowerCase();
  switch (lang) {
    case "typescript":
    case "typescriptreact":
    case "javascript":
    case "javascriptreact":
    case "jsx":
    case "vue":
    case "svelte":
    case "astro":
    case "scala":
    case "java":
    case "kotlin":
    case "csharp":
    case "cpp":
    case "go":
    case "rust":
    case "dart":
    case "php":
      return "code-ts";
    case "python":
    case "jupyter":
      return "code-py";
    case "markdown":
    case "mdx":
    case "restructuredtext":
    case "asciidoc":
      return "markdown";
    case "json":
    case "jsonc":
    case "json5":
    case "yaml":
    case "toml":
    case "ini":
    case "env":
    case "dotenv":
      return "data";
    default:
      return "generic";
  }
}

function looksBinaryContent(content: string): boolean {
  const sample = content.slice(0, 8000);
  if (sample.includes("\u0000")) return true;
  let weird = 0;
  for (let i = 0; i < sample.length; i++) {
    const code = sample.charCodeAt(i);
    // Teckenstyren (utom \t \n \r) räknas som skräp.
    if (code < 32 && code !== 9 && code !== 10 && code !== 13) weird++;
  }
  return sample.length > 0 && weird / sample.length > 0.08;
}

/** Sann om filen ser genererad ut: filnamn, lock-fil, eller genererings-header inom 3 första raderna. */
export function isGeneratedFile(path: string, content: string): boolean {
  const base = path.split(/[\\/]/).pop() ?? path;
  if (SKIP_BASENAME_RE.test(base)) return true;
  if (SKIP_BASENAME_RE2.test(base)) return true;
  if (/generated/i.test(base) && /(_|\.)generated(_|\.)|(generated)/i.test(base)) return true;
  const head = content.slice(0, 1200).toLowerCase();
  return GENERATED_HINTS.some((hint) => head.includes(hint));
}

/**
 * Returnerar en engelsk... ursäkt på svenska varför filen inte ska indexeras,
 * eller null om den är ok. Indexern loggar anledningen — tyst införlivning förbjuden.
 */
export function skipReason(input: {
  path: string;
  content?: string;
  sizeBytes?: number;
  maxFileBytes?: number;
}): string | null {
  const base = input.path.split(/[\\/]/).pop() ?? input.path;
  if (SKIP_BASENAME_RE.test(base)) return "lock-fil (genererad)";
  if (SKIP_BASENAME_RE2.test(base)) return "minifierad/map-fil (genererad)";
  const maxBytes = input.maxFileBytes ?? 512 * 1024;
  if (input.sizeBytes !== undefined && input.sizeBytes > maxBytes) {
    return `för stor (${input.sizeBytes} byte > ${maxBytes})`;
  }
  if (input.content === undefined) return null;
  if (looksBinaryContent(input.content)) return "binärt innehåll";
  if (isGeneratedFile(input.path, input.content)) return "genererad fil (header)";
  // Minifierad: få rader men enorm radbredd → inget meningsfullt radintervall.
  const lines = input.content.split(/\r?\n/);
  if (lines.length <= 8 && input.content.length > 4096) return "minifierad/en-radsfil";
  return null;
}

/** Deterministiskt chunk-id — samma rader i samma fil ger samma id (idempotent omlöp). */
export function chunkId(path: string, startLine: number, endLine: number, symbol?: string): string {
  const stem = symbol && symbol.length > 0 ? `:${symbol.replace(/\s+/g, "_")}` : "";
  return `${path}@${startLine}-${endLine}${stem}`;
}

