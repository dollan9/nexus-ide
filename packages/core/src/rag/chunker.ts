interface Region {
  startLine: number; // 0-baserat index i `lines`
  endLine: number; // 0-baserat, inclusive
  symbol?: string;
  kind: ChunkKind;
}

interface ScanState {
  inBlockComment: boolean;
  inString: string | null;
}

/**
 * Rader strukturen bevars men strängar, template-literaler och kommentarer ersätts
 * med blanksteg. Anledningen är helt enkla: antalet `{`/`}` måste vara litent för
 * att radnumren ska bli riktiga — en sträng `"{]"` får inte öppna ett block.
 */
function stripStructureLines(rawLines: string[], state: ScanState): string[] {
  const out: string[] = [];
  for (const raw of rawLines) {
    let acc = "";
    let i = 0;
    while (i < raw.length) {
      const ch = raw[i] ?? "";
      const next = raw[i + 1];
      if (state.inBlockComment) {
        if (ch === "*" && next === "/") {
          acc += "  ";
          state.inBlockComment = false;
          i += 2;
          continue;
        }
        acc += " ";
        i += 1;
        continue;
      }
      if (state.inString !== null) {
        if (ch === "\\") {
          acc += "  ";
          i += 2;
          continue;
        }
        if (ch === state.inString) {
          acc += " ";
          state.inString = null;
          i += 1;
          continue;
        }
        acc += " ";
        i += 1;
        continue;
      }
      if (ch === "/" && next === "/") {
        acc += " ".repeat(Math.max(0, raw.length - i));
        break;
      }
      if (ch === "/" && next === "*") {
        acc += "  ";
        state.inBlockComment = true;
        i += 2;
        continue;
      }
      if (ch === '"' || ch === "'" || ch === "`") {
        acc += " ";
        state.inString = ch;
        i += 1;
        continue;
      }
      acc += ch;
      i += 1;
    }
    // Enradiga strängar stängs vid radbrott (mallar och docstrings får fortsätta).
    if (state.inString === '"' || state.inString === "'") state.inString = null;
    out.push(acc);
  }
  return out;
}

const CONTROL_KEYWORDS = new Set([
  "if", "else", "for", "while", "do", "switch", "case", "default", "try", "catch",
  "finally", "return", "throw", "new", "delete", "typeof", "instanceof", "await",
  "yield", "super", "this", "function", "class", "const", "let", "var", "export",
  "import", "from", "async", "void", "in", "of", "get", "set",
]);

function countChar(s: string, ch: string): number {
  let n = 0;
  for (let i = 0; i < s.length; i++) if (s[i] === ch) n++;
  return n;
}

interface Frame {
  depthAtOpen: number;
  startLine: number;
  symbol?: string;
  isClass: boolean;
}

interface DeclHit {
  symbol: string;
  isClass: boolean;
}

const TS_FUNCTION = /^(?:export\s+)?(?:export\s+default\s+)?(?:declare\s+)?(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)/;
const TS_CLASS = /^(?:export\s+)?(?:declare\s+)?(?:abstract\s+)?class\s+([A-Za-z_$][\w$]*)/;
const TS_TYPEISH = /^(?:export\s+)?(?:declare\s+)?(?:abstract\s+)?(interface|enum|type|namespace|module)\s+([A-Za-z_$][\w$]*)/;
const TS_ARROW =
  /^(?:export\s+)?(?:declare\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?(?:function\b|\([^()]*\)\s*=>|[A-Za-z_$][\w$]*\s*=>|(?:async\s+)?class\b)/;
const TS_METHOD = /^(?:@\w+\s+)*(?:(?:public|private|protected|static|readonly|async|override|abstract|declare)\s+)*([A-Za-z_$][\w$]*)\s*(?:<[^()]*>)?\s*\(/;
const TS_CLASS_FIELD =
  /^(?:@\w+\s+)*(?:(?:public|private|protected|static|readonly)\s+)*([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?(?:\([^()]*\)|[A-Za-z_$][\w$]*)\s*=>/;
const TS_CTOR = /^(?:public\s+|private\s+|protected\s+)?constructor\s*\(/;

/** Matcha en deklarationsrubrik på en strukturerad (strippad) rad. */
function matchTsDecl(stripped: string, insideClass: boolean): DeclHit | null {
  const line = stripped.trimStart();
  if (line.length === 0) return null;

  const fn = TS_FUNCTION.exec(line);
  if (fn?.[1] && !CONTROL_KEYWORDS.has(fn[1])) return { symbol: fn[1], isClass: false };

  const cls = TS_CLASS.exec(line);
  if (cls?.[1]) return { symbol: cls[1], isClass: true };

  const typeish = TS_TYPEISH.exec(line);
  if (typeish?.[2]) return { symbol: typeish[2], isClass: false };

  const arrow = TS_ARROW.exec(line);
  if (arrow?.[1] && !CONTROL_KEYWORDS.has(arrow[1])) return { symbol: arrow[1], isClass: false };

  if (insideClass) {
    if (TS_CTOR.test(line)) return { symbol: "constructor", isClass: false };
    const field = TS_CLASS_FIELD.exec(line);
    if (field?.[1] && !CONTROL_KEYWORDS.has(field[1])) return { symbol: field[1], isClass: false };
    const method = TS_METHOD.exec(line);
    if (method?.[1] && !CONTROL_KEYWORDS.has(method[1])) return { symbol: method[1], isClass: false };
  }
  return null;
}

/**
 * TS/JS-likedespråk: spårar klamnedsdjup och binder deklarationer till block.
 * Toppnivå och nästlat hanteras av samma skanna — nästling städas bort i
 * regionsToChunks() där varje region bara får de rader som inga barn täcker.
 */
function detectTsRegions(lines: string[]): Region[] {
  const stripped = stripStructureLines(lines, { inBlockComment: false, inString: null });
  const regions: Region[] = [];
  const frames: Frame[] = [];
  let depth = 0;
  let pending: { symbol: string; startLine: number; depthAtOpen: number; isClass: boolean } | null = null;

  for (let i = 0; i < lines.length; i++) {
    const s = stripped[i] ?? "";
    const before = depth;
    const opens = countChar(s, "{") + countChar(s, "(") + countChar(s, "[");
    const closes = countChar(s, "}") + countChar(s, ")") + countChar(s, "]");
    // Endast klammer påverkar scopen; parenteser räknas bara för att hålla raden "sluten".
    depth += countChar(s, "{") - countChar(s, "}");
    if (depth < 0) depth = 0;

    const topFrame = frames[frames.length - 1];
    const insideClass = topFrame?.isClass === true;
    const hit: DeclHit | null = pending === null ? matchTsDecl(s, insideClass) : null;
    if (hit) {
      pending = { symbol: hit.symbol, startLine: i, depthAtOpen: before, isClass: hit.isClass };
    }

    const opened = depth > before;
    if (opened) {
      frames.push({
        depthAtOpen: before,
        startLine: pending ? pending.startLine : i,
        symbol: pending?.symbol,
        isClass: pending?.isClass === true,
      });
      pending = null;
    } else if (pending && (opens === 0 || closes > 0)) {
      // Deklaration utan block på samma rad (en-rads arrow, interface-header, typ-alias).
      regions.push({ startLine: pending.startLine, endLine: i, symbol: pending.symbol, kind: "symbol" });
      pending = null;
    }

    // Stäng ramar vars öppnande djup nåtts (djupet har fallit tillbaka till `depthAtOpen`).
    const after = depth;
    while (frames.length > 0) {
      const frame = frames[frames.length - 1];
      if (!frame || after > frame.depthAtOpen) break;
      frames.pop();
      if (frame.symbol) {
        regions.push({ startLine: frame.startLine, endLine: i, symbol: frame.symbol, kind: "symbol" });
      }
    }
    if (pending && pending.depthAtOpen < before && after <= pending.depthAtOpen) {
      pending = null;
    }
  }
  return dedupeRegions(regions);
}

const PY_DEF = /^(?:async\s+)?def\s+([A-Za-z_]\w*)\s*\(/;
const PY_CLASS = /^class\s+([A-Za-z_]\w*)/;

/** Python: indentering är syntax — blocket slutar där en icke-tom rad har mindre/equal indent. */
function detectPythonRegions(lines: string[]): Region[] {
  const stripped = stripStructureLines(lines, { inBlockComment: false, inString: null });
  const regions: Region[] = [];
  const stack: { indent: number; startLine: number; symbol: string; isClass: boolean }[] = [];

  const indentOf = (s: string): number => {
    let n = 0;
    while (n < s.length && (s[n] === " " || s[n] === "\t")) n++;
    return n;
  };

  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i] ?? "";
    const s = (stripped[i] ?? "").trim();
    const blank = s.length === 0;

    // Stäng block när en riktig kodrad hoppar ut i indent.
    if (!blank) {
      const ind = indentOf(raw);
      while (stack.length > 0) {
        const top = stack[stack.length - 1];
        if (!top || ind > top.indent) break;
        stack.pop();
        regions.push({ startLine: top.startLine, endLine: i - 1, symbol: top.symbol, kind: "symbol" });
      }
    }

    if (blank) continue;
    const body = raw.trimStart();
    const def = PY_DEF.exec(body);
    const cls = PY_CLASS.exec(body);
    const name = def?.[1] ?? cls?.[1];
    if (name && !CONTROL_KEYWORDS.has(name)) {
      // Dekoratorer hör till symbolen — backa över sammanhängande @-rader.
      let start = i;
      let probe = i - 1;
      while (probe >= 0) {
        const prev = (stripped[probe] ?? "").trim();
        if (/^@[\w.]+$/.test(prev)) {
          start = probe;
          probe--;
          continue;
        }
        break;
      }
      stack.push({ indent: indentOf(raw), startLine: start, symbol: name, isClass: Boolean(cls) });
    }
  }
  while (stack.length > 0) {
    const top = stack.pop();
    if (!top) break;
    regions.push({ startLine: top.startLine, endLine: lines.length - 1, symbol: top.symbol, kind: "symbol" });
  }
  return dedupeRegions(regions);
}

/** Markdown: rubriker delar dokumentet; kodstaket (` ``` `) räknas inte som rubriker. */
function detectMarkdownRegions(lines: string[]): Region[] {
  const regions: Region[] = [];
  let fence: string | null = null;
  const headings: { level: number; line: number; title: string }[] = [];
  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i] ?? "";
    const trimmed = raw.trimStart();
    if (trimmed.startsWith("```") || trimmed.startsWith("~~~")) {
      const marker = trimmed.slice(0, 3);
      fence = fence === null ? marker : null;
      continue;
    }
    if (fence !== null) continue;
    const m = /^(#{1,6})\s+(.+?)\s*$/.exec(raw);
    if (m?.[1] && m[2]) headings.push({ level: m[1].length, line: i, title: m[2] });
  }

  // Frontmatter (--- ... ---) överst är sitt eget dokument-avsnitt.
  if ((lines[0] ?? "").trim() === "---") {
    for (let i = 1; i < lines.length; i++) {
      if ((lines[i] ?? "").trim() === "---") {
        regions.push({ startLine: 0, endLine: i, symbol: "frontmatter", kind: "document" });
        break;
      }
    }
  }

  for (let h = 0; h < headings.length; h++) {
    const head = headings[h];
    if (!head) continue;
    let end = lines.length - 1;
    for (let n = h + 1; n < headings.length; n++) {
      const next = headings[n];
      if (next && next.level <= head.level) {
        end = next.line - 1;
        break;
      }
    }
    regions.push({ startLine: head.line, endLine: end, symbol: `#${head.title}`, kind: "section" });
  }
  return dedupeRegions(regions);
}

interface JsonPending {
  symbol: string;
  startLine: number;
  depthAtOpen: number;
}

/**
 * JSON/JSONC: nyckel på godtyckligt djup blir en region som slutar där värdet
 * slutar. Vi använder samma djupspår som kod-skannern, men strängkänslig
 * nyckelmatch (`"key":`) i stället för deklarationsregex.
 */
function detectJsonRegions(lines: string[]): Region[] {
  const stripped = stripStructureLines(lines, { inBlockComment: false, inString: null });
  const regions: Region[] = [];
  const frames: { startLine: number; depthAtOpen: number; symbol: string }[] = [];
  let depth = 0;
  let pending: JsonPending | null = null;

  for (let i = 0; i < lines.length; i++) {
    const s = stripped[i] ?? "";
    const before = depth;
    depth += countChar(s, "{") + countChar(s, "[") - countChar(s, "}") - countChar(s, "]");
    if (depth < 0) depth = 0;
    const keyMatch = /^\s*"([^"]{1,80})"\s*:/.exec(s);
    if (keyMatch?.[1] && !pending) pending = { symbol: keyMatch[1], startLine: i, depthAtOpen: before };

    if (depth > before && pending) {
      frames.push({ startLine: pending.startLine, depthAtOpen: before, symbol: pending.symbol });
      pending = null;
    } else if (pending && depth === before) {
      regions.push({ startLine: pending.startLine, endLine: i, symbol: pending.symbol, kind: "document" });
      pending = null;
    }

    while (frames.length > 0) {
      const frame = frames[frames.length - 1];
      if (!frame || depth > frame.depthAtOpen) break;
      frames.pop();
      regions.push({ startLine: frame.startLine, endLine: i, symbol: frame.symbol, kind: "document" });
    }
  }
  return dedupeRegions(regions);
}

/** YAML/TOML/INI: tumregel toppnivå-nyckel på indent 0, med `---` som dokumentgräns. */
function detectYamlRegions(lines: string[]): Region[] {
  const regions: Region[] = [];
  let start = -1;
  let symbol: string | undefined;
  const flush = (end: number): void => {
    if (start >= 0 && end >= start) {
      regions.push({ startLine: start, endLine: end, symbol, kind: "document" });
    }
    start = -1;
    symbol = undefined;
  };
  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i] ?? "";
    if (raw.trim() === "---") {
      flush(i - 1);
      continue;
    }
    if (/^[ \t]/.test(raw)) continue; // indent = tillhör föregående nyckel
    const m = /^([A-Za-z_$][\w.$-]*)\s*:/.exec(raw);
    if (m?.[1]) {
      flush(i - 1);
      start = i;
      symbol = m[1];
    }
  }
  flush(lines.length - 1);
  return dedupeRegions(regions);
}

function dedupeRegions(regions: Region[]): Region[] {
  const seen = new Map<string, Region>();
  for (const r of regions) {
    if (r.endLine < r.startLine) continue;
    const key = `${r.startLine}:${r.endLine}:${r.symbol ?? ""}`;
    if (!seen.has(key)) seen.set(key, r);
  }
  return [...seen.values()].sort((a, b) => a.startLine - b.startLine || b.endLine - a.endLine);
}

function detectRegions(lines: string[], family: ChunkFamily): Region[] {
  switch (family) {
    case "code-ts":
      return detectTsRegions(lines);
    case "code-py":
      return detectPythonRegions(lines);
    case "markdown":
      return detectMarkdownRegions(lines);
    case "data":
      return lines.some((l) => /^\s*[{[]/.test(l)) && !lines.some((l) => /^[A-Za-z_$][\w.$-]*:\s/.test(l))
        ? detectJsonRegions(lines)
        : detectYamlRegions(lines);
    default:
      return [];
  }
}

