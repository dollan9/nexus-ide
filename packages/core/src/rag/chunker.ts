function overlaps(start: number, end: number, region: Region): boolean {
  return region.startLine >= start && region.endLine <= end;
}

/** Kontinuerliga löp av rader i [start..end] som inga barnregioner täcker. */
function freeRuns(start: number, end: number, children: Region[]): { from: number; to: number }[] {
  const taken = new Uint8Array(end - start + 1);
  for (const c of children) {
    for (let l = Math.max(start, c.startLine); l <= Math.min(end, c.endLine); l++) taken[l - start] = 1;
  }
  const runs: { from: number; to: number }[] = [];
  let from = -1;
  for (let l = start; l <= end; l++) {
    const free = (taken[l - start] ?? 0) === 0;
    if (free && from < 0) from = l;
    if (!free && from >= 0) {
      runs.push({ from, to: l - 1 });
      from = -1;
    }
  }
  if (from >= 0) runs.push({ from, to: end });
  return runs;
}

function joinLines(lines: string[], from: number, to: number): string {
  return lines.slice(from, to + 1).join("\n");
}

/** En enskild rad som inte ryms inom budgeten skärs i teckenbitar — radnumret bevaras. */
function splitWideLine(text: string, maxChars: number, path: string, line: number, symbol?: string, kind: ChunkKind = "window"): ChunkDraft[] {
  const out: ChunkDraft[] = [];
  const stride = Math.max(1, maxChars - 200);
  for (let offset = 0; offset < text.length; offset += stride) {
    const piece = text.slice(offset, offset + maxChars);
    if (piece.trim().length === 0) continue;
    out.push({
      id: chunkId(path, line + 1, line + 1, `${symbol ?? "rad"}#${offset}`),
      path,
      startLine: line + 1,
      endLine: line + 1,
      text: piece,
      symbol,
      kind,
    });
  }
  return out;
}

/** Dela ett radlöp till bitar inom budgeten med överlappande rader. */
function windowRun(lines: string[], run: { from: number; to: number }, maxTokens: number, overlapLines: number, path: string, symbol: string | undefined, kind: ChunkKind, counter: { n: number }): ChunkDraft[] {
  const out: ChunkDraft[] = [];
  const maxChars = Math.max(64, Math.floor(maxTokens * CHARS_PER_TOKEN));
  let cursor = run.from;
  while (cursor <= run.to) {
    // En-rads-fall: raden i sig är för lång → teckenskär med bibehållet radnummer.
    const single = lines[cursor] ?? "";
    if (single.length > maxChars) {
      counter.n += 1;
      out.push(...splitWideLine(single, maxChars, path, cursor, symbol, kind));
      cursor += 1;
      continue;
    }
    let end = cursor;
    let acc = "";
    // Väx fönster rad för rad; stoppa precis förra budgeten överskrids. Första
    // raden är alltid med (den fångas av splitWideLine om den är för bred).
    while (end <= run.to) {
      const lineText = lines[end] ?? "";
      const candidate = end === cursor ? lineText : `${acc}\n${lineText}`;
      if (end > cursor && estimateTokens(candidate) > maxTokens) break;
      acc = candidate;
      end += 1;
    }
    const to = Math.min(Math.max(end - 1, cursor), run.to);
    const text = acc.length > 0 ? acc : joinLines(lines, cursor, to);
    counter.n += 1;
    const label = symbol ? (cursor === run.from ? symbol : `${symbol} (del ${counter.n})`) : undefined;
    out.push({
      id: chunkId(path, cursor + 1, to + 1, label),
      path,
      startLine: cursor + 1,
      endLine: to + 1,
      text,
      symbol: label,
      kind,
    });
    const step = Math.max(1, to - cursor + 1 - overlapLines);
    cursor = cursor + step;
    if (to === run.to) break;
  }
  return out;
}

/** Gemensamt slirpande fönster för okända språk — med overlap enligt briefen. */
function windowWholeFile(lines: string[], maxTokens: number, overlapLines: number, path: string): ChunkDraft[] {
  const counter = { n: 0 };
  return windowRun(lines, { from: 0, to: lines.length - 1 }, maxTokens, overlapLines, path, undefined, "window", counter);
}

/**
 * Region → chunks. Barnregioner tas bort ur föräldern så att radintervallen aldrig
 * överlappar: varje rad i filen tillhör exakt en chunk (utom överlappet i fönster).
 */
function regionsToChunks(path: string, lines: string[], regions: Region[], options: Required<ChunkerOptions>): ChunkDraft[] {
  const chunks: ChunkDraft[] = [];
  for (let r = 0; r < regions.length; r++) {
    const region = regions[r];
    if (!region) continue;
    const children = regions.filter((c, ci) => ci !== r && overlaps(region.startLine, region.endLine, c) && !(c.startLine === region.startLine && c.endLine === region.endLine));
    const runs = freeRuns(region.startLine, region.endLine, children);
    for (const run of runs) {
      const text = joinLines(lines, run.from, run.to);
      if (text.trim().length === 0) continue;
      if (estimateTokens(text) <= options.maxChunkTokens) {
        chunks.push({
          id: chunkId(path, run.from + 1, run.to + 1, region.symbol),
          path,
          startLine: run.from + 1,
          endLine: run.to + 1,
          text,
          symbol: region.symbol,
          kind: region.kind,
        });
        continue;
      }
      const counter = { n: 0 };
      chunks.push(
        ...windowRun(lines, run, options.maxChunkTokens, options.overlapLines, path, region.symbol, region.kind, counter),
      );
    }
  }
  return chunks;
}

function uncoveredRuns(lines: string[], regions: Region[]): { from: number; to: number }[] {
  if (regions.length === 0) return [{ from: 0, to: lines.length - 1 }];
  return freeRuns(0, lines.length - 1, regions);
}

/**
 * Huvudingången. Returnerar minst en chunk för allt icke-tomt innehåll och
 * garanterar att ingen chunk överskrider budgeten.
 */
export function chunkSource(input: {
  path: string;
  language: string;
  content: string;
  options?: ChunkerOptions;
}): ChunkDraft[] {
  const maxChunkTokens = Math.max(16, input.options?.maxChunkTokens ?? DEFAULT_MAX_CHUNK_TOKENS);
  const overlapLines = Math.max(0, input.options?.overlapLines ?? DEFAULT_OVERLAP_LINES);
  const maxChunksPerFile = Math.max(1, input.options?.maxChunksPerFile ?? DEFAULT_MAX_CHUNKS_PER_FILE);
  const options: Required<ChunkerOptions> = { maxChunkTokens, overlapLines, maxChunksPerFile };

  const lines = input.content.split(/\r?\n/);
  if (lines.length === 0 || input.content.trim().length === 0) return [];

  const family = chunkFamilyOf(input.language);
  const regions = detectRegions(lines, family);

  let chunks = regionsToChunks(input.path, lines, regions, options);

  // Rader som inga regioner fångade (importer, moduler-preamble, löpande text
  // mellan funktioner) får egna window-chunks — annars blir indexet ofullständigt.
  for (const run of uncoveredRuns(lines, regions)) {
    const text = joinLines(lines, run.from, run.to);
    if (text.trim().length === 0) continue;
    const counter = { n: 0 };
    if (estimateTokens(text) <= maxChunkTokens) {
      chunks.push({
        id: chunkId(input.path, run.from + 1, run.to + 1, undefined),
        path: input.path,
        startLine: run.from + 1,
        endLine: run.to + 1,
        text,
        kind: regions.length > 0 ? "body" : "window",
      });
    } else {
      chunks.push(...windowRun(lines, run, maxChunkTokens, overlapLines, input.path, undefined, regions.length > 0 ? "body" : "window", counter));
    }
  }

  if (chunks.length === 0) {
    chunks = windowWholeFile(lines, maxChunkTokens, overlapLines, input.path);
  }

  // Sortera och ta bort dubbletter på id (samma rader kan nås via flera regioner).
  const byId = new Map<string, ChunkDraft>();
  for (const c of chunks) if (!byId.has(c.id)) byId.set(c.id, c);
  const sorted = [...byId.values()].sort((a, b) => a.startLine - b.startLine || a.endLine - b.endLine);
  return sorted.slice(0, maxChunksPerFile);
}

/** Raden ur källan som en chunk påstås börja på — verifieringshjälp för tester och UI. */
export function lineAt(content: string, oneBasedLine: number): string | undefined {
  const lines = content.split(/\r?\n/);
  return lines[oneBasedLine - 1];
}
